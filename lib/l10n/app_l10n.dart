  /// Resolves an explicit language code, or auto-detects from the OS locale
  /// (defaulting to English `'en'`).
  static String resolveCode(String configured) {
    final clean = configured.trim().toLowerCase();
    if (_codes.contains(clean)) return clean;
    try {
      final sys = Platform.localeName.split(RegExp(r'[_-]')).first.toLowerCase();
      if (_codes.contains(sys)) return sys;
    } catch (_) {
      // Fallback to English
    }
    return 'en';
  }

  static AppL10n of(BuildContext context) {
    final scope = context.dependOnInheritedWidgetOfExactType<AppL10nScope>();
    return scope?.l10n ?? const AppL10n('en');
  }

  String t(String key, [Map<String, String> params = const {}]) {
    final table = _strings[code] ?? _strings['en']!;
    var value = table[key] ?? _strings['en']![key] ?? key;
    if (params.isNotEmpty) {
      params.forEach((k, v) {
        value = value.replaceAll('{$k}', v);
      });
    }
    return value;
  }

